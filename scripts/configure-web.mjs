import { readFile, writeFile } from 'node:fs/promises';
const headers = JSON.parse(await readFile(new URL('./security-headers.json', import.meta.url), 'utf8'));
const lines = Object.entries(headers).map(([name, value]) => {
  if (!/^[A-Za-z-]+$/.test(name) || /["\r\n\x00]/.test(value)) throw new Error('Invalid security header');
  return `    add_header ${name} "${value}" always;`;
});
await writeFile(new URL('./nginx-local.conf', import.meta.url), `# Generated by node scripts/configure-web.mjs from security-headers.json.
server {
    listen 80;
    server_name localhost;
    root /usr/share/nginx/html;
    index index.html;
    add_header Cache-Control "no-store" always;
${lines.join('\n')}
    location / {
        try_files $uri $uri/ /index.html;
    }
}
`);
